a = "Meezan is a good boy.\nHe is a good\t student." #\n is a new line escape sequence, \t is a tab escape sequence
print(a) 

b = "Meezan is a \"bad boy\"" #can use \" to print double quotes in a string
print(b)

c = "Jojo's bizzare \\adventure\\"
print(c)

d = "Jojo's bizzare \badventure" #\b is a backspace escape sequence
print(d)

print('It\'s a good day') #\ is used to escape the single quote in the string

print("JOJOs \rWorld") # Output: World


print("\U0001F600")
